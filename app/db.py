import array
import os
import time

import oracledb

DB_USER = os.getenv("DB_USER", "grupo3")
DB_PASSWORD = os.getenv("DB_PASSWORD", "grupo3")
DB_DSN = os.getenv("DB_DSN", "localhost:1521/FREEPDB1")

_pool: oracledb.ConnectionPool | None = None


def get_pool(tentativas: int = 60) -> oracledb.ConnectionPool:
    global _pool
    if _pool is not None:
        return _pool
    for i in range(1, tentativas + 1):
        try:
            pool = oracledb.create_pool(user=DB_USER, password=DB_PASSWORD, dsn=DB_DSN, min=1, max=4)
            with pool.acquire() as conn, conn.cursor() as cur:
                cur.execute("SELECT 1 FROM kb_docs WHERE 1 = 0")
            _pool = pool
            return _pool
        except oracledb.Error as e:
            print(f"Oracle ainda não está pronto ({i}/{tentativas}): {e}")
            time.sleep(5)
    raise RuntimeError("Não foi possível conectar no Oracle")


def _vetor(embedding: list[float]) -> array.array:
    return array.array("f", embedding)


def inserir_documento(titulo: str, texto: str, embedding: list[float]) -> int:
    with get_pool().acquire() as conn, conn.cursor() as cur:
        id_var = cur.var(int)
        cur.execute(
            """
            INSERT INTO kb_docs (titulo, texto, embedding)
            VALUES (:titulo, :texto, TO_VECTOR(:embedding, 384, FLOAT32))
            RETURNING id INTO :id
            """,
            titulo=titulo, texto=texto, embedding=_vetor(embedding), id=id_var,
        )
        conn.commit()
        return id_var.getvalue()[0]


def buscar_similares(embedding: list[float], top_k: int = 5) -> list[dict]:
    with get_pool().acquire() as conn, conn.cursor() as cur:
        cur.execute(
            """
            SELECT id,
                   titulo,
                   DBMS_LOB.SUBSTR(texto, 4000, 1) AS texto,
                   VECTOR_DISTANCE(embedding, TO_VECTOR(:pergunta, 384, FLOAT32), COSINE) AS distancia
            FROM kb_docs
            ORDER BY distancia
            FETCH FIRST :top_k ROWS ONLY
            """,
            pergunta=_vetor(embedding), top_k=top_k,
        )
        return [
            {"id": r[0], "titulo": r[1], "texto": r[2], "distancia": float(r[3])}
            for r in cur.fetchall()
        ]


def obter_embedding(doc_id: int) -> list[float] | None:
    with get_pool().acquire() as conn, conn.cursor() as cur:
        cur.execute("SELECT embedding FROM kb_docs WHERE id = :id", id=doc_id)
        row = cur.fetchone()
        return list(row[0]) if row else None


def listar_documentos() -> list[dict]:
    with get_pool().acquire() as conn, conn.cursor() as cur:
        cur.execute("SELECT id, titulo, created_at FROM kb_docs ORDER BY id")
        return [{"id": r[0], "titulo": r[1], "created_at": r[2].isoformat()} for r in cur.fetchall()]


def contar_documentos() -> int:
    with get_pool().acquire() as conn, conn.cursor() as cur:
        cur.execute("SELECT COUNT(*) FROM kb_docs")
        return cur.fetchone()[0]


def apagar_todos() -> None:
    with get_pool().acquire() as conn, conn.cursor() as cur:
        cur.execute("TRUNCATE TABLE kb_docs")
        cur.execute("ALTER TABLE kb_docs MODIFY id GENERATED BY DEFAULT AS IDENTITY (START WITH 1)")
